def _require(role: str, permission: str) -> None:
    normalized = (role or "candidate").strip().lower()
    permissions = ROLE_PERMISSIONS.get(normalized, set())
    if "*" in permissions or permission in permissions:
        return
    raise PermissionError(f"Role {normalized} cannot perform {permission}")


def _devnet_proof(kind: str, payload_hash: str) -> dict[str, str]:
    signature = _hash({"kind": kind, "payload_hash": payload_hash, "cluster": _cluster()})[:88]
    account = _hash({"account": kind, "payload_hash": payload_hash})[:44]
    return {
        "solana_signature": signature,
        "solana_account": account,
        "solana_cluster": _cluster(),
        "explorer_url": f"https://explorer.solana.com/tx/{signature}?cluster={_cluster()}",
    }


def _cluster() -> str:
    return os.getenv("SOLANA_CLUSTER", "devnet")


def _hash(value: Any) -> str:
    return hashlib.sha256(str(value).encode("utf-8")).hexdigest()


def _amount(value: Any) -> float:
    try:
        amount = float(value)
    except (TypeError, ValueError):
        raise ValueError("Amount must be numeric") from None
    if amount < 0:
        raise ValueError("Amount cannot be negative")
    return amount


def _env_bool(name: str, default: bool) -> bool:
    value = os.getenv(name)
    if value is None:
        return default
    return value.strip().lower() in {"1", "true", "yes", "on"}
